// Terms of use and privacy policy shown in the Mini App. Plain data so the bot or a
// public page can render the same text later.

export type LegalKind = 'terms' | 'privacy';

export interface LegalSection {
  title: string;
  /** Paragraphs; a line starting with "• " is rendered as a list item. */
  body: string[];
}

export interface LegalDoc {
  title: string;
  updated: string;
  intro: string;
  sections: LegalSection[];
}

export const LEGAL_UPDATED = '8 октября 2026 г.';

export function legalDoc(kind: LegalKind, supportUsername: string): LegalDoc {
  const support = supportUsername ? `@${supportUsername}` : 'поддержку через меню бота';
  return kind === 'terms' ? terms(support) : privacy(support);
}

