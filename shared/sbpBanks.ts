const normalize = (s: string) => s.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9]+/g, ' ').trim();

const INDEX = SBP_BANKS.map((b) => ({ bank: b, haystack: normalize(`${b.name} ${b.official ?? ''} ${b.aliases ?? ''}`) }));

/** Case/ё-insensitive search by any word prefix of the name, official name or aliases. */
export function searchBanks(query: string): SbpBank[] {
  const q = normalize(query);
  if (!q) return SBP_BANKS;
  const words = q.split(' ');
  return INDEX.filter(({ haystack }) => words.every((w) => haystack.includes(w))).map((x) => x.bank);
}

export function findBank(id: string): SbpBank | undefined {
  return SBP_BANKS.find((b) => b.id === id);
}
