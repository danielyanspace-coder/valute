// Data shapes exchanged between the backend, the Mini App and the admin panel.
import type { PayoutMethod, WithdrawalStatus } from './payout.js';
import type { FineInfo, OrderStatus, ServiceKind } from './services.js';

export interface MeDto {
  user: {
    id: number;
    telegramId: number;
    username: string | null;
    firstName: string;
    lastName: string | null;
    photoUrl: string | null;
  };
  /** Spendable balance, micro-USDT. */
  availableMicro: number;
  /** Locked in withdrawals that are not finished yet, micro-USDT. */
  frozenMicro: number;
  blocked: boolean;
  supportUsername: string;
  /**
   * Set while the operator asked the user to contact support and the deal is not finished:
   * the app shows a blocking screen and the server refuses money operations.
   */
  contactLock: { withdrawalId: number; amountRub: number } | null;
  /** Bot username without "@", for check links and the "@bot 10" hint. */
  botUsername: string;
  /** Profile numbers. An exchange is a completed USDT → RUB withdrawal. */
  stats: { exchanges: number; exchangedRub: number; memberSince: number };
}

/** Deposits: USDT on TRON (TRC-20) only. */
export interface DepositInfoDto {
  token: 'USDT';
  network: 'TRC20';
  networkName: string;
  /** The user's personal TRON address; null until address generation is set up. */
  address: string | null;
  minDepositMicro: number;
  confirmations: number;
  /** true in the standalone demo: the address is a fake placeholder. */
  demo?: boolean;
}

export interface CreateWithdrawalRequest {
  method: PayoutMethod;
  amountRub: number;
  phone?: string;
  bankId?: string;
  cardNumber?: string;
  /** Random id generated by the client, makes a repeated submit harmless. */
  requestId: string;
  platform?: string;
  acceptedTerms: true;
}

/** Withdrawal as the user sees it. */
export interface WithdrawalDto {
  id: number;
  method: PayoutMethod;
  status: WithdrawalStatus;
  amountRub: number;
  amountMicro: number;
  rate: number;
  /** "+7 912 345-67-89 · Сбербанк" or "МИР •• 9010". */
  destination: string;
  createdAt: number;
  sentAt: number | null;
  confirmDeadline: number | null;
  finishedAt: number | null;
  confirmedBy: 'user' | 'auto' | 'admin' | null;
  rejectReason: string | null;
  serverNow: number;
}

export type NotificationType =
  | 'confirm_receipt'
  | 'contact_support'
  | 'withdrawal_completed'
  | 'withdrawal_rejected'
  | 'transfer_received'
  | 'check_claimed'
  | 'order_paid'
  | 'order_rejected'
  | 'order_clarify'
  | 'deposit_credited';

export interface NotificationDto {
  id: number;
  type: NotificationType;
  withdrawalId: number | null;
  /** transfer_received: what arrived and from whom. */
  transfer?: TransferDto | null;
  /** check_claimed: the sender's check that was just activated. */
  check?: CheckDto | null;
  /** order_*: the service order whose status changed. */
  order?: ServiceOrderDto | null;
  /** deposit_credited: the deposit that just landed on the balance. */
  deposit?: DepositDto | null;
  createdAt: number;
}

/**
 * pending   seen in the chain, waiting for an irreversible (solidified) block
 * credited  on the balance
 * below_min smaller than the minimum, not credited (support can credit by hand)
 * held      AML check flagged the sender or could not run: an operator decides
 * rejected  operator refused to credit
 */
export type DepositStatus = 'pending' | 'credited' | 'below_min' | 'held' | 'rejected';

export interface DepositDto {
  id: number;
  status: DepositStatus;
  amountMicro: number;
  network: 'TRC20';
  txId: string;
  fromAddress: string | null;
  createdAt: number;
  creditedAt: number | null;
}

// ---------- Transfers and checks ----------

export interface PersonDto {
  username: string | null;
  firstName: string;
  photoUrl?: string | null;
}

export interface TransferDto {
  id: number;
  direction: 'in' | 'out';
  /** direct = by username, check = someone activated a check. */
  kind: 'direct' | 'check';
  amountMicro: number;
  counterparty: PersonDto;
  comment: string | null;
  createdAt: number;
}

export type CheckStatus = 'active' | 'claimed' | 'cancelled';

export interface CheckDto {
  id: number;
  code: string;
  amountMicro: number;
  comment: string | null;
  status: CheckStatus;
  createdAt: number;
  claimedAt: number | null;
  claimedBy: PersonDto | null;
  /** https://t.me/<bot>?start=c_<code> */
  link: string;
}

export interface SendTransferRequest {
  username: string;
  amount: string;
  comment?: string;
  requestId: string;
}

export interface CreateCheckRequest {
  amount: string;
  comment?: string;
  requestId: string;
}

// ---------- Services (fines, parking, Steam) ----------

export interface ServicesConfigDto {
  discountPercent: number;
  /** RUB per 1 USDT for services, already including the discount. */
  serviceRate: number;
  /** false until a fines data provider is configured: the user types the amount from the ruling. */
  fineLookupAvailable: boolean;
  steam: { minRub: number; maxRub: number };
  parking: { minRub: number; maxRub: number };
}

export type FineLookupDto = { found: true; fine: FineInfo } | { found: false; manual: boolean; message: string };

export interface CreateOrderRequest {
  kind: ServiceKind;
  requestId: string;
  /** fine */
  uin?: string;
  /** fine without a data provider, parking: rubles to pay */
  amountRub?: number;
  /** parking: phone of the parking account */
  phone?: string;
  /** steam */
  steamLogin?: string;
  /** steam: USDT the user spends */
  amountUsdt?: string;
  acceptedTerms: true;
}

export interface ServiceOrderDto {
  id: number;
  kind: ServiceKind;
  status: OrderStatus;
  amountRub: number;
  amountMicro: number;
  rate: number;
  discountPercent: number;
  /** How much the user saved vs. the exchange price, in rubles. */
  benefitRub: number;
  /** "УИН 1881…", "+7 912 …", "Логин steam_user" */
  target: string;
  fine: FineInfo | null;
  /** Operator's question when status is "clarify". */
  clarifyMessage: string | null;
  rejectReason: string | null;
  createdAt: number;
  finishedAt: number | null;
}

export type HistoryItem =
  | { type: 'withdrawal'; at: number; withdrawal: WithdrawalDto }
  | { type: 'order'; at: number; order: ServiceOrderDto }
  | { type: 'transfer'; at: number; transfer: TransferDto }
  | { type: 'check'; at: number; check: CheckDto }
  | { type: 'deposit'; at: number; deposit: DepositDto };

